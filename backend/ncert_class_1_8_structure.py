def get_syllabus_for_class(class_num):
    """Get syllabus structure for a specific class"""
    return NCERT_SYLLABUS_STRUCTURE.get(str(class_num), {})

def get_all_subjects_for_class(class_num):
    """Get list of all subjects for a class"""
    syllabus = get_syllabus_for_class(class_num)
    return list(syllabus.keys())

def get_chapters_for_subject(class_num, subject):
    """Get chapters for a specific subject"""
    syllabus = get_syllabus_for_class(class_num)
    subject_data = syllabus.get(subject, {})
    return subject_data.get('chapters', [])

